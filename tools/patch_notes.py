#!/usr/bin/env python3
"""Слой актуальности: что изменилось в игре после того, как гайд собрали.

Гайд (таблица Revan619) описывает билды по состоянию на патч 1.6.
Игра с тех пор получила один балансный патч — 1.6.1.493 от 30 июня 2026,
дальше только исправления багов (последний — хотфикс 1.6.1.514 от 20 июля).
Здесь эти изменения записываются в data.json: общий блок meta.patch
и пометка `warn` на тех билдах, которых изменения реально касаются.

Запуск последним в конвейере:
  python3 tools/patch_notes.py
"""
import json, re

CHECKED = '29 августа 2026'
GAME = '1.6.1.514'
GUIDE = '1.6'

NOTES = [
    'Эоганн ослаблен: «Эхо-импульс» больше не накладывается на союзников '
    'под «Гальваническим полем», дуговые винтовки не бьют по ним молниями, '
    'урон взрывов «Распределения заряда» снижен. Билды остались рабочими, но слабее.',
    '«Раненый зверь» и «Привечая конец» получили верхний предел бонуса — '
    'раньше они разгонялись бесконечно.',
    '«Осевая фортификация» Паскаля теперь увеличивает только урон от шока, а не весь входящий.',
    '«Хватка огрина» (аугментация на двуручное оружие в одной руке) усилена — '
    'штрафы к урону убраны, у MK-II небольшой бонус.',
    'Баг с посохами псайкера (их силы считаются атаками ближнего боя) не исправлен — '
    'билды гайда, построенные на нём, по-прежнему работают.',
]

# по каким названиям искать затронутые билды; None — у любого персонажа
FLAGS = [
    (None, ('Wounded Beast', 'Facing the End'),
     'Патч 1.6.1: у «Раненого зверя» и «Привечая конец» появился потолок бонуса — билд слабее, чем в гайде.'),
    # ослабили именно связки Эоганна, у остальных те же таланты работают как раньше
    ('eogunn', ('Echopulse', 'Galvanic Field', 'Charge Distribution', 'Servo-Skull Swarm'),
     'Патч 1.6.1: связки Эоганна через «Гальваническое поле» ослаблены — билд рабочий, но не такой сильный.'),
    ('pasqal', ('Axial Fortification',),
     'Патч 1.6.1: «Осевая фортификация» теперь усиливает только урон от шока, а не весь входящий.'),
]


def main():
    d = json.load(open('data.json', encoding='utf-8'))
    d['meta']['patch'] = {'game': GAME, 'guide': GUIDE, 'checked': CHECKED, 'notes': NOTES}
    n = 0
    for c in d['characters']:
        for b in c['builds']:
            blob = json.dumps(b, ensure_ascii=False)
            warns = [msg for who, names, msg in FLAGS
                     if (who is None or who == c['id'])
                     and any(re.search(re.escape(x), blob, re.I) for x in names)]
            if warns:
                b['warn'] = warns
                n += 1
            else:
                b.pop('warn', None)
    print(f'билдов с пометкой о патче: {n}')
    json.dump(d, open('data.json', 'w', encoding='utf-8'),
              ensure_ascii=False, separators=(',', ':'))
    print('data.json обновлён')


if __name__ == '__main__':
    main()
