def main_weapon(b):
    """первое оружие первого комплекта — по нему и судим о стиле боя"""
    sets = [items for slot, items in b.get('gear', []) if 'ружи' in slot.lower()]
    if not sets:
        return None, None
    first = sets[0].split('/')[0].strip().rstrip('.,')
    if not first:
        return None, None
    low = first.lower()
    flavor = next((f for rx, f in WEAPON if re.search(rx, low)), None)
    if flavor is None:                       # не опознали — смотрим весь комплект
        low = sets[0].lower()
        flavor = next((f for rx, f in WEAPON if re.search(rx, low)), None)
    return first, flavor


def weapon_line(b):
    first, flavor = main_weapon(b)
    if not first:
        return None
    return f'В руках — {first}' + (f': {flavor}.' if flavor else '.')


def ability_line(b):
    keys, ults = [], Counter()
    for rows in b['levels'].values():
        for row in rows:
            o = row[0]
            n = o.get('ru') or o['n']
            if o['t'] == 'key' and n not in keys:
                keys.append(n)
            if o['t'] == 'ult':
                ults[n] += 1
    out = []
    if ults:
        top = ults.most_common(1)[0][0]
        out.append(f'Главная кнопка каждого боя — «{top}»')
    if keys:
        out.append(('опора билда — ' if out else 'Опора билда — ')
                   + ', '.join(f'«{k}»' for k in keys[:3]))
    return ('; '.join(out) + '.') if out else None


def main():
    d = json.load(open('data.json', encoding='utf-8'))
    n = 0
    for c in d['characters']:
        for b in c['builds']:
            t1, t2 = b['tiers'][0], b['tiers'][1]
            parts = [T1.get(t1), T2.get(t2), weapon_line(b), ability_line(b), T3]
            b['feel'] = ' '.join(p for p in parts if p)
            short = SHORT.get(t2)
            if short:
                _, flavor = main_weapon(b)
                b['feelShort'] = short + '.' + (f' {flavor[0].upper()}{flavor[1:]}.' if flavor else '')
            n += 1
    print('описаний «как играется»:', n)
    json.dump(d, open('data.json', 'w', encoding='utf-8'),
              ensure_ascii=False, separators=(',', ':'))
    print('data.json обновлён')


if __name__ == '__main__':
    main()
